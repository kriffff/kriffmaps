// Writes dist/sw.js: a service worker that precaches every built file
// (app shell, JS/CSS, fonts, icons and the Tesseract OCR files) so KriffMaps
// works fully offline after the first visit. Runs after `vite build`.
//
// The cache name includes a hash of all file contents, so any change to the
// build produces a new service worker; the old cache is removed when the new
// one activates. Updates take effect on the next page load, never mid-session.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../dist", import.meta.url));
const SKIP = new Set(["sw.js", "_headers", "_redirects", "robots.txt"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(root)
  .map((path) => ({ path, url: "/" + relative(root, path).split(sep).join("/") }))
  .filter(({ url }) => !SKIP.has(url.slice(1)) && !url.endsWith(".map"))
  .sort((a, b) => a.url.localeCompare(b.url));

const hash = createHash("sha256");
for (const { path, url } of files) hash.update(url).update(readFileSync(path));
const version = hash.digest("hex").slice(0, 12);

// Cloudflare Pages redirects /index.html to /. Cache the shell under "/" so the
// worker never stores (and later serves) a redirect for page navigations.
const urls = files.map(({ url }) => (url === "/index.html" ? "/" : url));
const bytes = files.reduce((n, { path }) => n + statSync(path).size, 0);

const sw = `// Generated by scripts/generate-sw.mjs — do not edit.
const CACHE = "kriffmaps-${version}";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("kriffmaps-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // Every app route (/, /table, …) is the same single-page app shell. Real
  // files opened directly (e.g. /robots.txt, an icon) are served as themselves.
  const isFile = /\\.[a-z0-9]+$/i.test(url.pathname);
  if (request.mode === "navigate" && !isFile) {
    event.respondWith(
      caches.match("/").then((cached) => cached || fetch(request)),
    );
    return;
  }
  event.respondWith(caches.match(url.pathname).then((cached) => cached || fetch(request)));
});
`;

writeFileSync(join(root, "sw.js"), sw);
console.log(
  `Service worker: ${urls.length} files precached (${(bytes / 1048576).toFixed(1)} MB), cache kriffmaps-${version}`,
);
